# 专业模式有两种配色风格（普通模式永远暖棕，不参与切换）：
#   - dark：现在专业模式的深色终端风（保持原样，默认）
#   - warm：栗栗暖棕侦探风（普通模式那套，专业模式也能用）
# 白 / 灰 主题以后再加（2026-08-20 用户拍板「白到时再说」）。
#
# 这里只登记「有哪些主题 + 是否深色」，具体颜色仍写在 chat_dialog 的
# _apply_theme / _apply_launcher_theme / _ChatBubble 里。为什么不抽成一套
# 色板？因为深色是「终端块 + 等宽字体 + 方角」，暖棕是「圆角气泡 + ui 字体」，
# 两套视觉结构差异大，颜色能统一、结构统一不了，硬塞进一套色板只会更绕。
# ============================================================

# 显示顺序（默认深色排第一，专业模式一开始就是这个）
PRO_THEME_ORDER = ["dark", "warm"]

# 默认主题：深色（现状）
DEFAULT_PRO_THEME = "dark"

# 主题名 → 是否深色（决定 chat_dialog 走「终端块」还是「暖棕气泡」分支）
IS_DARK = {
    "dark": True,
    "warm": False,
}

# 主题名 → i18n 显示名 key（文案在 i18n/*.json，key 不存在则原样返回中文兜底）
THEME_LABEL_KEYS = {
    "dark": "theme.dark",
    "warm": "theme.warm",
}


def is_dark(name: str) -> bool:
    """主题名是否深色。非法名字按非深色（暖棕）处理。"""
    return IS_DARK.get(name, False)


# ============================================================
# 色板（Design Tokens）——把散落各面板的硬编码色值收进这里
# ============================================================
# 为什么抽色板：之前各面板（settings/viewer/pet/feature/chat）把色值硬编码在
# QSS 字符串里，同一个「正文深咖 #463329」在十几个文件重复写，看着像毛坯房、
# 改一处漏一处。这里用「语义角色」命名（bg/card/text/title/border/...），
# 各面板改从这里取，全局统一。
#
# 收编范围（2026-09-08 用户拍板）：
#   - 只收「值」不动「结构」：深色仍是「终端块+方角」、暖棕仍是「圆角气泡」，结构不变。
#   - 先收核心面板（chat/viewer/pet/feature/settings），小弹窗后置。
#   - 色值照搬现状，不做调色（保持暖棕原样）。
# 只收「语义角色」高频色；低频单文件专属色（如 #DDCCAE、#A98B6D）保持原样硬编码，
# 硬收成 token 只加一层间接、没收益。
# ============================================================

